# Builds Home5's background-shortcuts reader for the PS5 with the payload SDK.
#
#   PS5_PAYLOAD_SDK=/opt/ps5-payload-sdk MBEDTLS_LIB=.../libmbedtls.a MBEDTLS_INC=.../include \
#     H5_SRC=../src bash reader/build.sh
#
# Output in out/: reader.elf (the payload you load) and h5r_thread.elf (the SceShellUI thread, embedded in
# reader.elf). The ShellUI injector is fetched, unchanged, from ps5-dualsense-overlay (derived from Common
# FPS for PS5), with ptrace/ELF-loader helpers from shsrv (reader/pins.sh). All GPL-3.0-or-later.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
source "$here/pins.sh"
sdk=${PS5_PAYLOAD_SDK:?set PS5_PAYLOAD_SDK}
h5src=${H5_SRC:-$here/../src}
mbedtls_lib=${MBEDTLS_LIB:?set MBEDTLS_LIB to the console libmbedtls.a}
mbedtls_inc=${MBEDTLS_INC:?set MBEDTLS_INC to the mbedTLS include dir}
deps=$here/deps out=$here/out obj=$here/obj
rm -rf "$obj" && mkdir -p "$deps" "$out" "$obj"

fetch() { # dir url commit
    [ -d "$1/.git" ] || git clone -q "$2" "$1"
    git -C "$1" -c advice.detachedHead=false checkout -q "$3"
}
fetch "$deps/overlay" "$OVERLAY_URL" "$OVERLAY_COMMIT"
fetch "$deps/shsrv" "$SHSRV_URL" "$SHSRV_COMMIT"
vendor=$deps/overlay/src/ps5

CC=${PROSPERO_CC:-$sdk/bin/prospero-clang}
CXX=${PROSPERO_CXX:-$sdk/bin/prospero-clang++}

# The SceShellUI thread: a shared ELF with entry elf_main; the injector resolves its imports inside ShellUI.
"$CC" --target=x86_64-sie-ps5 -DPS5 -fPIC -fvisibility=hidden -march=znver2 -O2 -Wall -Wextra \
    -ffunction-sections -fdata-sections -shared \
    -Wl,--gc-sections -Wl,-Bsymbolic -Wl,-e,elf_main -Wl,-soname,libH5ShortcutsShellUI.so -Wl,-z,now \
    -Wl,--hash-style=sysv \
    -o "$out/h5r_thread.elf" "$here/h5r_thread.c" \
    -lkernel_sys -lSceLibcInternal -lScePad -lSceUserService

# The thread ELF as a byte array the loader injects directly.
python3 - "$out/h5r_thread.elf" "$obj/h5r_thread_blob.c" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* generated by reader/build.sh */\n")
    f.write("const unsigned char h5r_thread_elf[] = {" + ",".join(str(b) for b in data) + "};\n")
    f.write("const unsigned int h5r_thread_elf_len = %d;\n" % len(data))
PY

# The loader: the injector (overlay/shsrv, unchanged), Home5's Home Assistant client, and our code.
cflags=(-DPS5 -fPIC -fPIE -ffunction-sections -fdata-sections -march=znver2 -O2 -Wall -Wextra
        -I"$vendor" -I"$deps/shsrv" -I"$h5src" -I"$mbedtls_inc")
mbed=(-DMBEDTLS_USER_CONFIG_FILE="h5_mbedtls_config.h")
"$CC"  "${cflags[@]}" -Wno-unused-parameter -c "$vendor/stable_elfldr_bridge.c" -o "$obj/bridge.o"
"$CC"  "${cflags[@]}" -Wno-unused-parameter -c "$deps/shsrv/pt.c" -o "$obj/pt.o"
"$CC"  "${cflags[@]}" -std=c11 -c "$h5src/h5_base.c" -o "$obj/h5_base.o"
"$CC"  "${cflags[@]}" -std=c11 "${mbed[@]}" -c "$h5src/h5_net.c" -o "$obj/h5_net.o"
"$CC"  "${cflags[@]}" -std=c11 -c "$here/h5r_net.c" -o "$obj/h5r_net.o"
"$CC"  "${cflags[@]}" -std=c11 -c "$obj/h5r_thread_blob.c" -o "$obj/blob.o"
"$CXX" "${cflags[@]}" -std=c++20 -c "$vendor/stable_shellui_injector.cpp" -o "$obj/injector.o"
"$CXX" "${cflags[@]}" -std=c++20 -c "$vendor/remote_call.cpp" -o "$obj/remote_call.o"
"$CXX" "${cflags[@]}" -std=c++20 -c "$here/h5r_loader.cpp" -o "$obj/loader.o"
"$CXX" -Wl,--gc-sections -o "$out/reader.elf" "$obj/"*.o "$mbedtls_lib" \
    -lkernel_sys -lSceLibcInternal -lSceNotification -lSceNet

sha256sum "$out/reader.elf" "$out/h5r_thread.elf"
